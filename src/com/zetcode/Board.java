package com.zetcode;

import javax.swing.JPanel;
import javax.swing.Timer;
import java.awt.Color;
import java.awt.Dimension;
import java.awt.Font;
import java.awt.FontMetrics;
import java.awt.Graphics;
import java.awt.Graphics2D;
import java.awt.Point;
import java.awt.RenderingHints;
import java.awt.Toolkit;
import java.awt.event.ActionEvent;
import java.awt.event.ActionListener;
import java.awt.event.KeyAdapter;
import java.awt.event.KeyEvent;

// BUILDER CLIENT uses the director 
public class Board extends JPanel {

    private Timer timer;
    private String message = "Game Over";
    private Ball ball;
    private Paddle paddle;
    private Brick[] bricks;
    private boolean inGame = true;

    private static final int MESSAGE_TICKS = 750;

    // COMPOSITE: the tree
    private GameObject world;

    // DECORATOR: the tree, with or without a message
    private GameObject scene;

    private int messageTicks;
    private int bricksBroken;

    
    private final LevelBuilder levelBuilder;

    //builder received from Breakout
    public Board(LevelBuilder levelBuilder) {

        this.levelBuilder = levelBuilder;

        initBoard();
    }

    private void initBoard() {

        addKeyListener(new TAdapter());
        setFocusable(true);
        setPreferredSize(new Dimension(Commons.WIDTH, Commons.HEIGHT));

        gameInit();
    }

    private void gameInit() {

        
        var director = new LevelDirector(levelBuilder);
        director.makeLevel();

        //هنا كل المعمعة خلصت بس نستخرج الليفل
        Level level = director.getLevel();

        paddle = level.getPaddle();
        ball = level.getBall();
        bricks = level.getBricks();

        // COMPOSITE CLIENT (slide 40): build the tree
        GameObject brickGroup = new GameObjectGroup();
        for (int i = 0; i < bricks.length; i++) {
            brickGroup.add(bricks[i]);
        }

        world = new GameObjectGroup();
        world.add(ball);
        world.add(paddle);
        world.add(brickGroup);

        showMessage("Use LEFT / RIGHT to move");

        timer = new Timer(Commons.PERIOD, new GameCycle());
        timer.start();
    }

    @Override
    public void paintComponent(Graphics g) {
        super.paintComponent(g);

        var g2d = (Graphics2D) g;

        g2d.setRenderingHint(RenderingHints.KEY_ANTIALIASING,
                RenderingHints.VALUE_ANTIALIAS_ON);

        g2d.setRenderingHint(RenderingHints.KEY_RENDERING,
                RenderingHints.VALUE_RENDER_QUALITY);

        if (inGame) {

            drawObjects(g2d);
        } else {

            gameFinished(g2d);
        }

        Toolkit.getDefaultToolkit().sync();
    }

    private void drawObjects(Graphics2D g2d) {

        // COMPOSITE + DECORATOR CLIENT: one call draws the whole tree
        scene.draw(g2d);
    }

    private void gameFinished(Graphics2D g2d) {

        var font = new Font("Verdana", Font.BOLD, 18);
        FontMetrics fontMetrics = this.getFontMetrics(font);

        g2d.setColor(Color.BLACK);
        g2d.setFont(font);
        g2d.drawString(message,
                (Commons.WIDTH - fontMetrics.stringWidth(message)) / 2,
                Commons.WIDTH / 2);
    }

    private class TAdapter extends KeyAdapter {

        @Override
        public void keyReleased(KeyEvent e) {

            paddle.keyReleased(e);
        }

        @Override
        public void keyPressed(KeyEvent e) {

            paddle.keyPressed(e);
        }
    }

    private class GameCycle implements ActionListener {

        @Override
        public void actionPerformed(ActionEvent e) {

            doGameCycle();
        }
    }

    private void doGameCycle() {

        ball.move();
        paddle.move();
        checkCollision();
        hideMessageWhenTimeIsUp();
        repaint();
    }

    private void showMessage(String text) {

        // DECORATOR CLIENT (slide 52): wrap the tree
        scene = new MessageDecorator(world, text);
        messageTicks = MESSAGE_TICKS;
    }

    private void hideMessageWhenTimeIsUp() {

        if (messageTicks > 0) {

            messageTicks--;

            if (messageTicks == 0) {

                // DECORATOR: responsibility withdrawn (slide 54)
                scene = world;
            }
        }
    }

    private void stopGame() {

        inGame = false;
        timer.stop();
    }

    private void checkCollision() {

        if (ball.getRect().getMaxY() > Commons.BOTTOM_EDGE) {

            stopGame();
        }

        
        for (int i = 0, j = 0; i < bricks.length; i++) {

            if (bricks[i].isDestroyed()) {

                j++;
            }

            if (j == bricks.length) {

                message = "Victory";
                stopGame();
            }
        }

        if ((ball.getRect()).intersects(paddle.getRect())) {

            int paddleLPos = (int) paddle.getRect().getMinX();
            int ballLPos = (int) ball.getRect().getMinX();

            int first = paddleLPos + 8;
            int second = paddleLPos + 16;
            int third = paddleLPos + 24;
            int fourth = paddleLPos + 32;

            if (ballLPos < first) {

                ball.setXDir(-1);
                ball.setYDir(-1);
            }

            if (ballLPos >= first && ballLPos < second) {

                ball.setXDir(-1);
                ball.setYDir(-1 * ball.getYDir());
            }

            if (ballLPos >= second && ballLPos < third) {

                ball.setXDir(0);
                ball.setYDir(-1);
            }

            if (ballLPos >= third && ballLPos < fourth) {

                ball.setXDir(1);
                ball.setYDir(-1 * ball.getYDir());
            }

            if (ballLPos > fourth) {

                ball.setXDir(1);
                ball.setYDir(-1);
            }
        }

        
        for (int i = 0; i < bricks.length; i++) {

            if ((ball.getRect()).intersects(bricks[i].getRect())) {

                int ballLeft = (int) ball.getRect().getMinX();
                int ballHeight = (int) ball.getRect().getHeight();
                int ballWidth = (int) ball.getRect().getWidth();
                int ballTop = (int) ball.getRect().getMinY();

                var pointRight = new Point(ballLeft + ballWidth + 1, ballTop);
                var pointLeft = new Point(ballLeft - 1, ballTop);
                var pointTop = new Point(ballLeft, ballTop - 1);
                var pointBottom = new Point(ballLeft, ballTop + ballHeight + 1);

                if (!bricks[i].isDestroyed()) {

                    if (bricks[i].getRect().contains(pointRight)) {

                        ball.setXDir(-1);
                    } else if (bricks[i].getRect().contains(pointLeft)) {

                        ball.setXDir(1);
                    }

                    if (bricks[i].getRect().contains(pointTop)) {

                        ball.setYDir(1);
                    } else if (bricks[i].getRect().contains(pointBottom)) {

                        ball.setYDir(-1);
                    }

                    bricks[i].setDestroyed(true);
                    bricksBroken++;

                    if (bricksBroken == 5) {

                        showMessage("Great job!");
                    }

                    if (bricksBroken == bricks.length / 2) {

                        showMessage("Halfway there!");
                    }
                }
            }
        }
    }
}
